NxPacketCodec::NxPacketCodec(bool transform_payload)
    : transform_payload_(transform_payload) {}

std::vector<NxPacket> NxPacketCodec::Feed(std::span<const std::uint8_t> bytes) {
  std::vector<NxPacket> packets;
  while (!bytes.empty()) {
    if (pending_.size() < kHeaderSize) {
      const auto count = std::min(kHeaderSize - pending_.size(), bytes.size());
      pending_.insert(pending_.end(), bytes.begin(), bytes.begin() + count);
      bytes = bytes.subspan(count);
      if (pending_.size() < kHeaderSize) {
        break;
      }
    }

    const auto length = ReadWord(pending_.data());
    if (length > kMaxPayloadSize) {
      Reset();
      throw std::invalid_argument(
          "NxPacket length would overflow the client's 16-bit total length");
    }

    const auto total = kHeaderSize + length;
    const auto count = std::min(total - pending_.size(), bytes.size());
    pending_.insert(pending_.end(), bytes.begin(), bytes.begin() + count);
    bytes = bytes.subspan(count);
    if (pending_.size() < total) {
      break;
    }

    NxPacket packet;
    packet.message_id = ReadWord(pending_.data() + 2);
    packet.payload.assign(pending_.begin() + kHeaderSize, pending_.end());
    if (transform_payload_) {
      Transform(packet.payload, packet.message_id);
    }
    packets.push_back(std::move(packet));
    pending_.clear();
  }

  return packets;
}

std::vector<std::uint8_t> NxPacketCodec::Encode(const NxPacket& packet) const {
  if (packet.payload.size() > kMaxPayloadSize) {
    throw std::invalid_argument(
        "NxPacket payload exceeds the compatible size limit");
  }

  const auto length = static_cast<std::uint16_t>(packet.payload.size());
  std::vector<std::uint8_t> bytes{
      static_cast<std::uint8_t>(length), static_cast<std::uint8_t>(length >> 8),
      static_cast<std::uint8_t>(packet.message_id),
      static_cast<std::uint8_t>(packet.message_id >> 8)};
  bytes.insert(bytes.end(), packet.payload.begin(), packet.payload.end());
  if (transform_payload_) {
    Transform(std::span<std::uint8_t>(bytes).subspan(kHeaderSize),
              packet.message_id);
  }

  return bytes;
}

void NxPacketCodec::Reset() { pending_.clear(); }
