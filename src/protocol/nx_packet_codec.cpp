std::uint16_t ReadWord(const std::uint8_t* bytes) {
  return static_cast<std::uint16_t>(
      bytes[0] | (static_cast<std::uint16_t>(bytes[1]) << 8));
}

void Transform(std::span<std::uint8_t> payload, std::uint16_t message_id) {
  const auto key = kKeyTable[(payload.size() + message_id) % kKeyTable.size()];
  for (std::size_t index = 0; index < payload.size(); ++index) {
    payload[index] ^= static_cast<std::uint8_t>(key % (index + 1) + key);
  }
}
